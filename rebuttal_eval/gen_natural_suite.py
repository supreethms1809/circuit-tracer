"""REQ-5: held-out natural-text benchmark manifest from wikitext validation.

Draws fixed-seed random windows from the wikitext-2 validation split (held
out from training, which used the train split), sets the target token to the
corpus's actual next token and the foil to a frequency-matched random token,
and writes a runnable suite JSON by cloning an existing suite's structure
(stages, dataset, model_variants, evaluation) and swapping the benchmark.

Entries use family="factual" with split="natural_heldout" — the split field
carries the natural-text designation so no live eval-path config change is
needed. The selection rule is recorded in the manifest to pre-empt any
cherry-picking concern (spec §3).

Usage:
  python -m rebuttal_eval.gen_natural_suite \
      --template experiments/paper_configs/suites/paper_gpt2_small_ravel_spline_dt12288.json \
      --suite-name paper_gpt2_small_natural_spline_fm_v3 \
      --output experiments/paper_configs/suites/paper_gpt2_small_natural_spline_fm_v3.json \
      [--model gpt2] [--n-prompts 200] [--window-len 32] [--seed 101]
"""

from __future__ import annotations

import argparse
import collections
import json
import random
import sys
from pathlib import Path

from rebuttal_eval.common import git_sha


def build_entries(
    model_name: str, n_prompts: int, window_len: int, seed: int
) -> list[dict[str, object]]:
    from datasets import load_dataset
    from transformers import AutoTokenizer

    tokenizer = AutoTokenizer.from_pretrained(model_name)
    dataset = load_dataset(
        "Salesforce/wikitext", "wikitext-2-raw-v1", split="validation"
    )
    token_stream: list[int] = []
    for row in dataset:
        if row["text"].strip():
            token_stream.extend(tokenizer(row["text"])["input_ids"])

    # Corpus unigram counts for frequency-matched foils.
    counts = collections.Counter(token_stream)
    by_frequency = sorted(counts, key=counts.__getitem__)
    rank_of = {token: rank for rank, token in enumerate(by_frequency)}

    rng = random.Random(seed)
    n_windows_available = (len(token_stream) - 1) // window_len
    starts = rng.sample(range(n_windows_available), min(n_prompts, n_windows_available))

    entries = []
    for index, window_index in enumerate(sorted(starts)):
        start = window_index * window_len
        window = token_stream[start : start + window_len]
        target = token_stream[start + window_len]
        # Frequency-matched foil: a different token from the +-10 rank
        # neighborhood of the target's corpus frequency rank.
        rank = rank_of[target]
        low = max(0, rank - 10)
        neighborhood = [
            t for t in by_frequency[low : rank + 11] if t != target
        ]
        foil = rng.choice(neighborhood) if neighborhood else target
        entries.append(
            {
                "prompt_id": f"natural_{index:04d}",
                "family": "factual",
                "prompt": tokenizer.decode(window),
                "target_token": tokenizer.decode([target]),
                "foil_token": tokenizer.decode([foil]),
                "split": "natural_heldout",
                "include_macag": False,
            }
        )
    return entries


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--template", required=True,
                        help="Existing suite JSON to clone structure from")
    parser.add_argument("--suite-name", required=True)
    parser.add_argument("--output", required=True)
    parser.add_argument("--model", default="gpt2",
                        help="Tokenizer for windowing (must match the suite's base model)")
    parser.add_argument("--n-prompts", type=int, default=200)
    parser.add_argument("--window-len", type=int, default=32)
    parser.add_argument("--seed", type=int, default=101)
    args = parser.parse_args(argv)

    suite = json.loads(Path(args.template).read_text())
    entries = build_entries(args.model, args.n_prompts, args.window_len, args.seed)

    suite["suite_name"] = args.suite_name
    suite["benchmark_manifest_version"] = "natural-wikitext-v1"
    suite["benchmark_entries"] = entries
    suite["description"] = (
        f"Held-out natural text replacement-fidelity benchmark: "
        f"{len(entries)} fixed-seed (seed={args.seed}) random {args.window_len}-token "
        f"windows from wikitext-2-raw-v1 validation (held out from training); "
        f"target = actual next token, foil = frequency-matched random token "
        f"(rank +-10 neighborhood). Generated by rebuttal_eval.gen_natural_suite "
        f"at git {git_sha()}. Cloned structure from {args.template}."
    )
    if "output_dir" in suite:
        suite["output_dir"] = str(
            Path(suite["output_dir"]).parent / args.suite_name
        )

    output_path = Path(args.output)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(json.dumps(suite, indent=2))
    print(
        f"wrote {len(entries)} natural-text entries to {output_path} "
        f"(suite {args.suite_name})"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
